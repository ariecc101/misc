#!/usr/bin/env bash
#
# ubuntu-repo-reset.sh
# Kembalikan APT source Ubuntu ke upstream resmi:
#   - amd64/i386     : archive.ubuntu.com + security.ubuntu.com
#   - arch lain      : ports.ubuntu.com/ubuntu-ports (arm64, armhf, ppc64el, s390x, riscv64)
#   - rilis EOL      : old-releases.ubuntu.com (terdeteksi otomatis)
# Format otomatis: klasik (/etc/apt/sources.list) untuk <24.04,
#                  deb822 (/etc/apt/sources.list.d/ubuntu.sources) untuk >=24.04.
#
set -euo pipefail

SCRIPT_NAME=$(basename "$0")
SCHEME="http"
COMPONENTS="main restricted universe multiverse"
DRY_RUN=0
DO_UPDATE=1
FORCE_EOL=0
WITH_SRC=0
ASSUME_YES=0

log()  { printf '[*] %s\n' "$*"; }
warn() { printf '[!] %s\n' "$*" >&2; }
die()  { printf '[x] %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<EOF
Pemakaian: sudo $SCRIPT_NAME [opsi]

  -n, --dry-run          Tampilkan hasil saja, tidak mengubah apa pun
  -y, --yes              Tanpa konfirmasi
      --https            Pakai https:// (butuh paket ca-certificates)
      --eol              Paksa old-releases.ubuntu.com (rilis sudah EOL)
      --src              Aktifkan baris deb-src
  -c, --components "..." Default: "$COMPONENTS"
      --no-update        Jangan jalankan apt-get update
  -h, --help             Bantuan
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -n|--dry-run)  DRY_RUN=1 ;;
    -y|--yes)      ASSUME_YES=1 ;;
    --https)       SCHEME="https" ;;
    --eol)         FORCE_EOL=1 ;;
    --src)         WITH_SRC=1 ;;
    --no-update)   DO_UPDATE=0 ;;
    -c|--components) shift; [[ $# -gt 0 ]] || die "Opsi -c butuh argumen"; COMPONENTS="$1" ;;
    -h|--help)     usage; exit 0 ;;
    *)             usage; die "Opsi tidak dikenal: $1" ;;
  esac
  shift
done

# ---------- Deteksi sistem ----------
[[ -r /etc/os-release ]] || die "/etc/os-release tidak ditemukan"
# shellcheck disable=SC1091
. /etc/os-release
[[ "${ID:-}" == "ubuntu" ]] || die "Ini bukan Ubuntu (ID=${ID:-?}). Script dihentikan."

CODENAME="${VERSION_CODENAME:-${UBUNTU_CODENAME:-}}"
[[ -n "$CODENAME" ]] || die "Codename Ubuntu tidak terdeteksi"
MAJOR="${VERSION_ID%%.*}"
ARCH=$(dpkg --print-architecture)

if (( DRY_RUN == 0 )) && [[ $EUID -ne 0 ]]; then
  die "Jalankan sebagai root (sudo), atau pakai --dry-run"
fi

case "$ARCH" in
  amd64|i386)
    MAIN="${SCHEME}://archive.ubuntu.com/ubuntu"
    SEC="${SCHEME}://security.ubuntu.com/ubuntu"
    ;;
  *)
    MAIN="${SCHEME}://ports.ubuntu.com/ubuntu-ports"
    SEC="$MAIN"
    ;;
esac

# ---------- Deteksi EOL ----------
url_ok() {
  if command -v curl >/dev/null 2>&1; then
    curl -fsIL --max-time 20 "$1" >/dev/null 2>&1
  elif command -v wget >/dev/null 2>&1; then
    wget -q --spider --timeout=20 "$1" >/dev/null 2>&1
  else
    return 2
  fi
}

if (( FORCE_EOL == 0 )); then
  rc=0
  url_ok "$MAIN/dists/$CODENAME/Release" || rc=$?
  if [[ $rc -eq 1 ]]; then
    warn "Rilis '$CODENAME' tidak ada di $MAIN -> dianggap EOL, pakai old-releases."
    FORCE_EOL=1
  elif [[ $rc -eq 2 ]]; then
    warn "curl/wget tidak ada, pengecekan EOL dilewati (pakai --eol jika perlu)."
  fi
fi

if (( FORCE_EOL )); then
  MAIN="${SCHEME}://old-releases.ubuntu.com/ubuntu"
  SEC="$MAIN"
fi

# ---------- Pilih format ----------
if [[ "$MAJOR" =~ ^[0-9]+$ ]] && (( MAJOR >= 24 )); then
  FORMAT="deb822"
else
  FORMAT="classic"
fi

log "Ubuntu $VERSION_ID ($CODENAME), arch=$ARCH, format=$FORMAT"
log "Main     : $MAIN"
log "Security : $SEC"
log "Komponen : $COMPONENTS"

if (( DRY_RUN == 0 )) && (( ASSUME_YES == 0 )) && [[ -t 0 ]]; then
  read -r -p "Lanjut mengganti sumber APT? [y/N] " ans
  [[ "$ans" =~ ^[Yy]$ ]] || die "Dibatalkan."
fi

# ---------- Generator ----------
gen_classic() {
  echo "# Official Ubuntu repositories - generated by $SCRIPT_NAME on $(date -u +%F)"
  local suite
  for suite in "$CODENAME" "$CODENAME-updates" "$CODENAME-backports"; do
    echo "deb $MAIN $suite $COMPONENTS"
    (( WITH_SRC )) && echo "deb-src $MAIN $suite $COMPONENTS"
  done
  echo "deb $SEC $CODENAME-security $COMPONENTS"
  (( WITH_SRC )) && echo "deb-src $SEC $CODENAME-security $COMPONENTS"
  return 0
}

gen_deb822() {
  local types="deb"
  (( WITH_SRC )) && types="deb deb-src"
  cat <<EOF
# Official Ubuntu repositories - generated by $SCRIPT_NAME on $(date -u +%F)
Types: $types
URIs: $MAIN
Suites: $CODENAME $CODENAME-updates $CODENAME-backports
Components: $COMPONENTS
Signed-By: /usr/share/keyrings/ubuntu-archive-keyring.gpg

Types: $types
URIs: $SEC
Suites: $CODENAME-security
Components: $COMPONENTS
Signed-By: /usr/share/keyrings/ubuntu-archive-keyring.gpg
EOF
}

write_file() {  # write_file <dest>  (isi dari stdin)
  local dest="$1" tmp
  tmp=$(mktemp)
  cat >"$tmp"
  if (( DRY_RUN )); then
    echo "----- $dest -----"
    cat "$tmp"
    echo
    rm -f "$tmp"
  else
    install -m 0644 "$tmp" "$dest"
    rm -f "$tmp"
  fi
}

# ---------- Backup ----------
SRC_LIST="/etc/apt/sources.list"
SRC_DEB822="/etc/apt/sources.list.d/ubuntu.sources"

if (( DRY_RUN == 0 )); then
  BACKUP_DIR="/etc/apt/sources-backup-$(date +%Y%m%d-%H%M%S)"
  mkdir -p "$BACKUP_DIR"
  [[ -f "$SRC_LIST"   ]] && cp -a "$SRC_LIST"   "$BACKUP_DIR/"
  [[ -f "$SRC_DEB822" ]] && cp -a "$SRC_DEB822" "$BACKUP_DIR/"
  log "Backup disimpan di $BACKUP_DIR"
fi

# ---------- Tulis konfigurasi ----------
if [[ "$FORMAT" == "deb822" ]]; then
  [[ -f /usr/share/keyrings/ubuntu-archive-keyring.gpg ]] || \
    warn "ubuntu-archive-keyring.gpg tidak ada; install paket ubuntu-keyring."
  gen_deb822 | write_file "$SRC_DEB822"
  printf '# Ubuntu sources have moved to %s\n' "$SRC_DEB822" | write_file "$SRC_LIST"
else
  gen_classic | write_file "$SRC_LIST"
  # hapus ubuntu.sources (mis. sisa upgrade) agar tidak duplikat
  if [[ -f "$SRC_DEB822" ]]; then
    if (( DRY_RUN )); then
      log "[dry-run] akan menghapus $SRC_DEB822 (sudah dibackup)"
    else
      rm -f "$SRC_DEB822"
    fi
  fi
fi

# ---------- Cegah cloud-init menimpa ulang ----------
if [[ -d /etc/cloud/cloud.cfg.d ]]; then
  printf 'apt_preserve_sources_list: true\n' | write_file /etc/cloud/cloud.cfg.d/99-preserve-apt-sources.cfg
fi

# ---------- Update ----------
if (( DO_UPDATE )) && (( DRY_RUN == 0 )); then
  log "Menjalankan apt-get update ..."
  apt-get update
fi

log "Selesai."
if (( DRY_RUN == 0 )); then
  echo "Rollback : cp -a $BACKUP_DIR/* /etc/apt/ (sesuaikan lokasi file) lalu apt-get update"
  echo "Catatan  : PPA/repo pihak ketiga di /etc/apt/sources.list.d/ tidak diubah."
fi
